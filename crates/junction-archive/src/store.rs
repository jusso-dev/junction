#[derive(Debug, Clone)]
pub struct HttpRequest {
    pub method: &'static str,
    pub url: Url,
    pub headers: Vec<(String, String)>,
    pub body: Vec<u8>,
}

#[derive(Debug, Clone)]
pub struct HttpReply {
    pub status: u16,
    pub headers: Vec<(String, String)>,
    pub body: Vec<u8>,
}

impl HttpReply {
    pub fn header(&self, name: &str) -> Option<&str> {
        self.headers
            .iter()
            .find(|(k, _)| k.eq_ignore_ascii_case(name))
            .map(|(_, v)| v.as_str())
    }
    fn success(&self) -> bool {
        (200..300).contains(&self.status)
    }
}

/// Sends storage requests. Tests script replies; production uses [`LiveHttp`].
pub trait Http: Send + Sync {
    fn send(&self, request: HttpRequest) -> BoxFut<'_, Result<HttpReply>>;
}

/// HTTPS only, no redirects, bounded response bodies.
pub struct LiveHttp {
    client: reqwest::Client,
}

impl LiveHttp {
    pub fn new(timeout: Duration) -> Result<Self> {
        let client = reqwest::Client::builder()
            .https_only(true)
            .redirect(reqwest::redirect::Policy::none())
            .timeout(timeout)
            .build()
            .map_err(|_| anyhow::anyhow!("storage transport initialisation failed"))?;
        Ok(Self { client })
    }
}

impl Http for LiveHttp {
    fn send(&self, request: HttpRequest) -> BoxFut<'_, Result<HttpReply>> {
        Box::pin(async move {
            let method = reqwest::Method::from_bytes(request.method.as_bytes())?;
            let mut builder = self.client.request(method, request.url);
            for (name, value) in &request.headers {
                let mut value = reqwest::header::HeaderValue::from_str(value)
                    .map_err(|_| anyhow::anyhow!("invalid storage header"))?;
                if name.eq_ignore_ascii_case("authorization") {
                    value.set_sensitive(true);
                }
                builder = builder.header(name.as_str(), value);
            }
            let mut response = builder
                .body(request.body)
                .send()
                .await
                .map_err(|_| anyhow::anyhow!("storage request failed"))?;
            let status = response.status().as_u16();
            let headers = response
                .headers()
                .iter()
                .filter_map(|(k, v)| Some((k.as_str().to_owned(), v.to_str().ok()?.to_owned())))
                .collect();
            if response
                .content_length()
                .is_some_and(|n| n > MAX_READ_BYTES as u64)
            {
                bail!("storage response size limit exceeded");
            }
            let mut body = Vec::new();
            while let Some(chunk) = response
                .chunk()
                .await
                .map_err(|_| anyhow::anyhow!("storage response failed"))?
            {
                if body.len() + chunk.len() > MAX_READ_BYTES {
                    bail!("storage response size limit exceeded");
                }
                body.extend_from_slice(&chunk);
            }
            Ok(HttpReply {
                status,
                headers,
                body,
            })
        })
    }
}

/// Retry throttling and transient server errors, honouring `Retry-After`.
#[derive(Debug, Clone, Copy)]
pub struct Retry {
    pub attempts: u32,
    pub base: Duration,
    pub cap: Duration,
}

impl Default for Retry {
    fn default() -> Self {
        Self {
            attempts: 5,
            base: Duration::from_millis(500),
            cap: Duration::from_secs(30),
        }
    }
}

impl Retry {
    pub const IMMEDIATE: Self = Self {
        attempts: 5,
        base: Duration::ZERO,
        cap: Duration::ZERO,
    };

    async fn send(
        &self,
        http: &dyn Http,
        build: impl Fn() -> Result<HttpRequest>,
    ) -> Result<HttpReply> {
        let mut attempt = 0;
        loop {
            let reply = http.send(build()?).await;
            let transient = match &reply {
                Ok(r) => matches!(r.status, 408 | 429 | 500 | 502 | 503 | 504),
                Err(_) => true,
            };
            if !transient || attempt + 1 >= self.attempts {
                return reply;
            }
            let server = reply
                .as_ref()
                .ok()
                .and_then(|r| r.header("retry-after"))
                .and_then(|v| v.trim().parse::<u64>().ok())
                .map(Duration::from_secs);
            let delay = server
                .unwrap_or_else(|| self.base.saturating_mul(1 << attempt.min(16)))
                .min(self.cap);
            if !delay.is_zero() {
                tokio::time::sleep(delay).await;
            }
            attempt += 1;
        }
    }
}

/// Short, secret-free description of a failed storage reply.
fn failure(what: &str, reply: &HttpReply) -> anyhow::Error {
    let code = reply
        .header("x-ms-error-code")
        .map(str::to_owned)
        .or_else(|| xml_first(&reply.body, "Code"))
        .filter(|c| c.len() <= 64 && c.bytes().all(|b| b.is_ascii_alphanumeric()));
    match code {
        Some(code) => anyhow::anyhow!("{what} failed: HTTP {} {code}", reply.status),
        None => anyhow::anyhow!("{what} failed: HTTP {}", reply.status),
    }
}

