/// A local directory. Create-only and read-only files, but **not immutable**:
/// anyone with access to the host can delete it. For tests and trials only.
pub struct LocalStore {
    root: PathBuf,
}

impl LocalStore {
    pub fn new(root: &Path) -> Result<Self> {
        std::fs::create_dir_all(root).context("local archive directory unavailable")?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(root, std::fs::Permissions::from_mode(0o700))?;
        }
        Ok(Self {
            root: root.to_path_buf(),
        })
    }
    fn path(&self, key: &str) -> Result<PathBuf> {
        validate_key(key)?;
        Ok(self.root.join(key))
    }
    fn put_sync(&self, key: &str, bytes: &[u8]) -> Result<PutOutcome> {
        use std::io::Write;
        let path = self.path(key)?;
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        let tmp = path.with_extension(format!("tmp-{}", std::process::id()));
        {
            let mut file = std::fs::OpenOptions::new()
                .write(true)
                .create_new(true)
                .open(&tmp)
                .context("local archive write failed")?;
            file.write_all(bytes)?;
            file.sync_all()?;
        }
        // hard_link fails if the target exists: create-only, never a replace.
        let linked = std::fs::hard_link(&tmp, &path);
        let _ = std::fs::remove_file(&tmp);
        match linked {
            Ok(()) => {
                let mut perms = std::fs::metadata(&path)?.permissions();
                perms.set_readonly(true);
                std::fs::set_permissions(&path, perms)?;
                Ok(PutOutcome::Created)
            }
            Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {
                Ok(PutOutcome::AlreadyExists)
            }
            Err(_) => bail!("local archive write failed"),
        }
    }
    fn list_sync(&self, prefix: &str) -> Result<Vec<String>> {
        validate_prefix(prefix)?;
        let mut out = Vec::new();
        let mut stack = vec![self.root.clone()];
        while let Some(dir) = stack.pop() {
            let Ok(entries) = std::fs::read_dir(&dir) else {
                continue;
            };
            for entry in entries.flatten() {
                let path = entry.path();
                let file_type = entry.file_type()?;
                if file_type.is_dir() {
                    stack.push(path);
                } else if file_type.is_file()
                    && let Ok(rel) = path.strip_prefix(&self.root)
                    && let Some(key) = rel.to_str()
                {
                    let key = key.replace('\\', "/");
                    if key.starts_with(prefix) && !key.contains(".tmp-") {
                        out.push(key);
                    }
                }
            }
        }
        out.sort();
        Ok(out)
    }
}

impl ObjectStore for LocalStore {
    fn describe(&self) -> String {
        format!("local directory {} (not immutable)", self.root.display())
    }
    fn put_new<'a>(
        &'a self,
        key: &'a str,
        bytes: Vec<u8>,
        _: &'a str,
    ) -> BoxFut<'a, Result<PutOutcome>> {
        Box::pin(async move { self.put_sync(key, &bytes) })
    }
    fn get<'a>(&'a self, key: &'a str) -> BoxFut<'a, Result<Option<Vec<u8>>>> {
        Box::pin(async move {
            match std::fs::read(self.path(key)?) {
                Ok(bytes) => Ok(Some(bytes)),
                Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
                Err(_) => bail!("local archive read failed"),
            }
        })
    }
    fn list<'a>(&'a self, prefix: &'a str) -> BoxFut<'a, Result<Vec<String>>> {
        Box::pin(async move { self.list_sync(prefix) })
    }
    fn hold<'a>(&'a self, key: &'a str, hold_id: &'a str) -> BoxFut<'a, Result<HoldOutcome>> {
        Box::pin(async move {
            let bytes = std::fs::read(self.path(key)?).context("held object unavailable")?;
            let held = hold_key(hold_id, key)?;
            self.put_sync(&held, &bytes)?;
            Ok(HoldOutcome {
                method: "copied_to_hold_prefix",
                held_key: held,
            })
        })
    }
    fn release<'a>(&'a self, _: &'a str) -> BoxFut<'a, Result<()>> {
        Box::pin(async move { Ok(()) })
    }
    fn delete_refused<'a>(&'a self, _: &'a str) -> BoxFut<'a, Result<bool>> {
        // A local directory cannot refuse its owner. Report it as such.
        Box::pin(async move { Ok(false) })
    }
    fn retention_until<'a>(&'a self, _: &'a str) -> BoxFut<'a, Result<Option<String>>> {
        Box::pin(async move { Ok(None) })
    }
}

