// Minimal XML reading for listing responses

/// Text of every element named `name` whose parent is `parent` (any parent when None).
fn xml_texts(body: &[u8], parent: Option<&str>, name: &str) -> Result<Vec<String>> {
    use quick_xml::{Reader, events::Event};
    let text = std::str::from_utf8(body).map_err(|_| anyhow::anyhow!("listing is not UTF-8"))?;
    let mut reader = Reader::from_str(text);
    let mut stack: Vec<String> = Vec::new();
    let mut out = Vec::new();
    let mut current: Option<String> = None;
    loop {
        match reader
            .read_event()
            .map_err(|_| anyhow::anyhow!("malformed storage listing"))?
        {
            Event::Start(start) => {
                let local = start.local_name().as_ref().to_owned();
                if stack.len() > 32 {
                    bail!("storage listing too deep");
                }
                let matches =
                    local == name && parent.is_none_or(|p| stack.last().is_some_and(|s| s == p));
                stack.push(local);
                if matches {
                    current = Some(String::new());
                }
            }
            Event::End(_) => {
                if let (Some(value), Some(top)) = (current.take(), stack.last())
                    && top == name
                {
                    out.push(value);
                }
                stack.pop();
            }
            Event::Text(t) => {
                if let Some(value) = current.as_mut() {
                    value.push_str(&t.xml10_content());
                }
            }
            Event::GeneralRef(r) => {
                if let Some(value) = current.as_mut() {
                    let c = r
                        .resolve_char_ref()
                        .ok()
                        .flatten()
                        .or(match r.as_ref() {
                            "amp" => Some('&'),
                            "lt" => Some('<'),
                            "gt" => Some('>'),
                            "quot" => Some('"'),
                            "apos" => Some('\''),
                            _ => None,
                        })
                        .ok_or_else(|| anyhow::anyhow!("unsupported XML entity"))?;
                    value.push(c);
                }
            }
            Event::DocType(_) => bail!("XML document type declarations are not supported"),
            Event::Eof => break,
            _ => {}
        }
    }
    Ok(out)
}

fn xml_first(body: &[u8], name: &str) -> Option<String> {
    xml_texts(body, None, name).ok()?.into_iter().next()
}

