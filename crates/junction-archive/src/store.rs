//! Customer-owned object storage: Azure Blob, Cloudflare R2 and a local
//! directory for tests and trials.
//!
//! Every write is a create-only put (`If-None-Match: *`). Immutability itself
//! is the storage service's job: Azure version-level immutability on the
//! container, or an R2 bucket lock rule. Junction never sets, shortens or
//! removes retention, so a compromised host running Junction cannot rewrite
//! the archive either.
use anyhow::{Context, Result, bail};
use junction_watch::{clock::Instant, event::sha256_hex};
use ring::hmac;
use std::{
    future::Future,
    path::{Path, PathBuf},
    pin::Pin,
    sync::Arc,
    time::{Duration, SystemTime},
};
use tokio::sync::Mutex;
use url::Url;
use zeroize::Zeroizing;

pub type BoxFut<'a, T> = Pin<Box<dyn Future<Output = T> + Send + 'a>>;

/// Azure Storage REST version. Legal hold and immutability headers need 2020-06-12 or later.
pub const AZURE_STORAGE_VERSION: &str = "2023-11-03";
/// Token audience for Azure Storage data-plane requests.
pub const AZURE_STORAGE_AUDIENCE: &str = "https://storage.azure.com";
/// Largest object body read back from storage.
pub const MAX_READ_BYTES: usize = 256 * 1024 * 1024;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PutOutcome {
    Created,
    /// An object with this key already exists. Keys are content hashes, so this
    /// is a replay of a batch already stored.
    AlreadyExists,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HoldOutcome {
    /// How the hold was applied: `legal_hold_flag` or `copied_to_hold_prefix`.
    pub method: &'static str,
    /// Key now holding the protected copy (the original key for Azure).
    pub held_key: String,
}

/// Storage the archive writes to. Errors never carry credentials or bodies.
pub trait ObjectStore: Send + Sync {
    /// Short human description without secrets, for status output.
    fn describe(&self) -> String;
    fn put_new<'a>(
        &'a self,
        key: &'a str,
        bytes: Vec<u8>,
        content_type: &'a str,
    ) -> BoxFut<'a, Result<PutOutcome>>;
    fn get<'a>(&'a self, key: &'a str) -> BoxFut<'a, Result<Option<Vec<u8>>>>;
    /// Every key under `prefix`, in lexicographic order.
    fn list<'a>(&'a self, prefix: &'a str) -> BoxFut<'a, Result<Vec<String>>>;
    /// Protect one object past its normal retention.
    fn hold<'a>(&'a self, key: &'a str, hold_id: &'a str) -> BoxFut<'a, Result<HoldOutcome>>;
    /// Release a hold applied by [`hold`](Self::hold). On R2 and the local
    /// store the held copy stays until the hold-prefix lock rule is changed by
    /// an administrator; Junction only records the release.
    fn release<'a>(&'a self, key: &'a str) -> BoxFut<'a, Result<()>>;
    /// Try to delete `key`. Used only by `doctor` on its own canary, to prove
    /// the storage refuses deletion. Returns true if the delete was refused.
    fn delete_refused<'a>(&'a self, key: &'a str) -> BoxFut<'a, Result<bool>>;
    /// Retention reported by the service for `key`, if it reports one.
    fn retention_until<'a>(&'a self, key: &'a str) -> BoxFut<'a, Result<Option<String>>>;
}

/// Object keys are generated by Junction; refuse anything that could escape a
/// prefix or a local directory.
pub fn validate_key(key: &str) -> Result<()> {
    if key.is_empty()
        || key.len() > 1024
        || key.starts_with('/')
        || key.ends_with('/')
        || key.contains("//")
        || key.split('/').any(|s| s == "." || s == "..")
        || !key
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'/' | b'.' | b'_' | b'-' | b'='))
    {
        bail!("invalid object key");
    }
    Ok(())
}

fn validate_prefix(prefix: &str) -> Result<()> {
    if prefix.is_empty() {
        return Ok(());
    }
    validate_key(prefix.trim_end_matches('/'))
}

/// `holds/<hold-id>/<original key>`
pub fn hold_key(hold_id: &str, key: &str) -> Result<String> {
    validate_hold_id(hold_id)?;
    let held = format!("holds/{hold_id}/{key}");
    validate_key(&held)?;
    Ok(held)
}

pub fn validate_hold_id(id: &str) -> Result<()> {
    if id.is_empty()
        || id.len() > 64
        || !id
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'-' | b'_'))
    {
        bail!("hold id must be 1-64 letters, digits, - or _");
    }
    Ok(())
}

