/// Supplies Entra access tokens for Azure Storage.
pub trait TokenSource: Send + Sync {
    fn token(&self) -> BoxFut<'_, Result<Zeroizing<String>>>;
}

/// A fixed token, for tests.
pub struct StaticToken(pub String);
impl TokenSource for StaticToken {
    fn token(&self) -> BoxFut<'_, Result<Zeroizing<String>>> {
        Box::pin(async move { Ok(Zeroizing::new(self.0.clone())) })
    }
}

/// Tokens from Junction's environment credential flows (certificate, client
/// secret, managed or workload identity), cached until shortly before expiry.
pub struct EnvironmentTokens {
    request: junction_auth::TokenRequest,
    cached: Mutex<Option<Arc<junction_auth::AccessToken>>>,
}

impl EnvironmentTokens {
    pub fn new(
        tenant: &str,
        authority: &str,
        flow: junction_auth::AuthFlow,
        profile: &str,
    ) -> Self {
        Self {
            request: junction_auth::TokenRequest {
                tenant: tenant.to_owned(),
                authority: authority.to_owned(),
                audience: AZURE_STORAGE_AUDIENCE.to_owned(),
                scopes: vec![],
                credential_profile: profile.to_owned(),
                flow,
                api_key: None,
            },
            cached: Mutex::new(None),
        }
    }
}

impl TokenSource for EnvironmentTokens {
    fn token(&self) -> BoxFut<'_, Result<Zeroizing<String>>> {
        Box::pin(async move {
            let mut cached = self.cached.lock().await;
            if let Some(token) = cached.as_ref()
                && token.metadata().expires_at > SystemTime::now() + Duration::from_secs(300)
            {
                return Ok(Zeroizing::new(token.expose().to_owned()));
            }
            let credential =
                junction_auth::environment::EnvironmentCredential::from_environment_for(
                    &self.request.flow,
                )
                .map_err(|_| {
                    anyhow::anyhow!("storage credential unavailable in the environment")
                })?;
            let token = credential
                .acquire(&self.request)
                .await
                .map_err(|_| anyhow::anyhow!("storage token could not be obtained"))?;
            let value = Zeroizing::new(token.expose().to_owned());
            *cached = Some(Arc::new(token));
            Ok(value)
        })
    }
}

/// Azure Blob container with version-level immutability enabled by the operator.
pub struct AzureBlobStore {
    account: Url,
    container: String,
    http: Arc<dyn Http>,
    tokens: Arc<dyn TokenSource>,
    retry: Retry,
}

const AZURE_SUFFIXES: [&str; 3] = [
    ".blob.core.windows.net",
    ".blob.core.usgovcloudapi.net",
    ".blob.core.chinacloudapi.cn",
];

impl AzureBlobStore {
    pub fn new(
        account_url: &str,
        container: &str,
        http: Arc<dyn Http>,
        tokens: Arc<dyn TokenSource>,
        retry: Retry,
    ) -> Result<Self> {
        let account = parse_account_url(account_url)?;
        validate_container(container)?;
        Ok(Self {
            account,
            container: container.to_owned(),
            http,
            tokens,
            retry,
        })
    }

    fn url(&self, key: Option<&str>, query: &[(&str, &str)]) -> Result<Url> {
        let mut url = self.account.clone();
        {
            let mut segments = url
                .path_segments_mut()
                .map_err(|_| anyhow::anyhow!("invalid account URL"))?;
            segments.clear().push(&self.container);
            if let Some(key) = key {
                validate_key(key)?;
                segments.extend(key.split('/'));
            }
        }
        if !query.is_empty() {
            url.query_pairs_mut().extend_pairs(query);
        }
        Ok(url)
    }

    async fn request(
        &self,
        method: &'static str,
        url: Url,
        extra: &[(&str, String)],
        body: Vec<u8>,
    ) -> Result<HttpReply> {
        let token = self.tokens.token().await?;
        self.retry
            .send(self.http.as_ref(), || {
                let mut headers = vec![
                    (
                        "authorization".to_owned(),
                        format!("Bearer {}", token.as_str()),
                    ),
                    ("x-ms-version".to_owned(), AZURE_STORAGE_VERSION.to_owned()),
                    (
                        "x-ms-date".to_owned(),
                        httpdate::fmt_http_date(SystemTime::now()),
                    ),
                ];
                headers.extend(extra.iter().map(|(k, v)| ((*k).to_owned(), v.clone())));
                Ok(HttpRequest {
                    method,
                    url: url.clone(),
                    headers,
                    body: body.clone(),
                })
            })
            .await
    }
}

pub fn parse_account_url(value: &str) -> Result<Url> {
    let url = Url::parse(value.trim()).map_err(|_| anyhow::anyhow!("account_url must be a URL"))?;
    let host = url.host_str().unwrap_or_default().to_ascii_lowercase();
    if url.scheme() != "https"
        || !url.username().is_empty()
        || url.password().is_some()
        || url.query().is_some()
        || url.fragment().is_some()
        || url.path() != "/"
        || !AZURE_SUFFIXES.iter().any(|s| host.ends_with(s))
    {
        bail!(
            "account_url must be a storage account blob endpoint such as https://<account>.blob.core.windows.net/ with no path, query or SAS token"
        );
    }
    Ok(url)
}

fn validate_container(name: &str) -> Result<()> {
    let ok = (3..=63).contains(&name.len())
        && name
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
        && !name.starts_with('-')
        && !name.ends_with('-')
        && !name.contains("--");
    if !ok {
        bail!("container must be 3-63 lower-case letters, digits and single hyphens");
    }
    Ok(())
}

impl ObjectStore for AzureBlobStore {
    fn describe(&self) -> String {
        format!("Azure Blob {}{}", self.account.as_str(), self.container)
    }
    fn put_new<'a>(
        &'a self,
        key: &'a str,
        bytes: Vec<u8>,
        content_type: &'a str,
    ) -> BoxFut<'a, Result<PutOutcome>> {
        Box::pin(async move {
            let url = self.url(Some(key), &[])?;
            let reply = self
                .request(
                    "PUT",
                    url,
                    &[
                        ("x-ms-blob-type", "BlockBlob".to_owned()),
                        ("if-none-match", "*".to_owned()),
                        ("content-type", content_type.to_owned()),
                    ],
                    bytes,
                )
                .await?;
            match reply.status {
                201 => Ok(PutOutcome::Created),
                // If-None-Match: * on an existing blob.
                409 | 412 => Ok(PutOutcome::AlreadyExists),
                _ => Err(failure("archive write", &reply)),
            }
        })
    }
    fn get<'a>(&'a self, key: &'a str) -> BoxFut<'a, Result<Option<Vec<u8>>>> {
        Box::pin(async move {
            let reply = self
                .request("GET", self.url(Some(key), &[])?, &[], vec![])
                .await?;
            match reply.status {
                200 => Ok(Some(reply.body)),
                404 => Ok(None),
                _ => Err(failure("archive read", &reply)),
            }
        })
    }
    fn list<'a>(&'a self, prefix: &'a str) -> BoxFut<'a, Result<Vec<String>>> {
        Box::pin(async move {
            validate_prefix(prefix)?;
            let mut keys = Vec::new();
            let mut marker: Option<String> = None;
            for _ in 0..100_000 {
                let mut query = vec![
                    ("restype", "container"),
                    ("comp", "list"),
                    ("prefix", prefix),
                    ("maxresults", "5000"),
                ];
                if let Some(m) = marker.as_deref() {
                    query.push(("marker", m));
                }
                let reply = self
                    .request("GET", self.url(None, &query)?, &[], vec![])
                    .await?;
                if !reply.success() {
                    return Err(failure("archive listing", &reply));
                }
                for key in xml_texts(&reply.body, Some("Blob"), "Name")? {
                    if key.starts_with(prefix) && validate_key(&key).is_ok() {
                        keys.push(key);
                    }
                }
                match xml_first(&reply.body, "NextMarker").filter(|m| !m.is_empty()) {
                    Some(next) if Some(&next) != marker.as_ref() => marker = Some(next),
                    Some(_) => bail!("archive listing did not advance"),
                    None => {
                        keys.sort();
                        keys.dedup();
                        return Ok(keys);
                    }
                }
            }
            bail!("archive listing did not terminate")
        })
    }
    fn hold<'a>(&'a self, key: &'a str, _: &'a str) -> BoxFut<'a, Result<HoldOutcome>> {
        Box::pin(async move {
            let url = self.url(Some(key), &[("comp", "legalhold")])?;
            let reply = self
                .request(
                    "PUT",
                    url,
                    &[("x-ms-legal-hold", "true".to_owned())],
                    vec![],
                )
                .await?;
            if reply.status != 200 || reply.header("x-ms-legal-hold") != Some("true") {
                return Err(failure("legal hold", &reply));
            }
            Ok(HoldOutcome {
                method: "legal_hold_flag",
                held_key: key.to_owned(),
            })
        })
    }
    fn release<'a>(&'a self, key: &'a str) -> BoxFut<'a, Result<()>> {
        Box::pin(async move {
            let url = self.url(Some(key), &[("comp", "legalhold")])?;
            let reply = self
                .request(
                    "PUT",
                    url,
                    &[("x-ms-legal-hold", "false".to_owned())],
                    vec![],
                )
                .await?;
            if reply.status != 200 {
                return Err(failure("legal hold release", &reply));
            }
            Ok(())
        })
    }
    fn delete_refused<'a>(&'a self, key: &'a str) -> BoxFut<'a, Result<bool>> {
        Box::pin(async move {
            let reply = self
                .request("DELETE", self.url(Some(key), &[])?, &[], vec![])
                .await?;
            Ok(!reply.success())
        })
    }
    fn retention_until<'a>(&'a self, key: &'a str) -> BoxFut<'a, Result<Option<String>>> {
        Box::pin(async move {
            let reply = self
                .request("HEAD", self.url(Some(key), &[])?, &[], vec![])
                .await?;
            if !reply.success() {
                return Err(failure("archive properties", &reply));
            }
            Ok(reply
                .header("x-ms-immutability-policy-until-date")
                .map(str::to_owned))
        })
    }
}

