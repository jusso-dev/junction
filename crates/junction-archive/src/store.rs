/// R2 access key pair from the environment. Never read from configuration.
pub struct R2Credentials {
    pub access_key_id: String,
    pub secret_access_key: Zeroizing<String>,
}

pub const R2_ACCESS_KEY_ENV: &str = "JUNCTION_ARCHIVE_R2_ACCESS_KEY_ID";
pub const R2_SECRET_KEY_ENV: &str = "JUNCTION_ARCHIVE_R2_SECRET_ACCESS_KEY";

impl R2Credentials {
    pub fn from_environment() -> Result<Self> {
        let read = |name: &str| {
            std::env::var(name)
                .ok()
                .filter(|v| !v.trim().is_empty())
                .ok_or_else(|| anyhow::anyhow!("{name} is not set"))
        };
        Ok(Self {
            access_key_id: read(R2_ACCESS_KEY_ENV)?,
            secret_access_key: Zeroizing::new(read(R2_SECRET_KEY_ENV)?),
        })
    }
}

/// Cloudflare R2 bucket protected by bucket lock rules set by an administrator.
pub struct R2Store {
    endpoint: Url,
    bucket: String,
    credentials: R2Credentials,
    http: Arc<dyn Http>,
    retry: Retry,
    clock: fn() -> Instant,
}

impl R2Store {
    /// `jurisdiction` is `default`, `eu` or `fedramp`.
    pub fn new(
        account_id: &str,
        jurisdiction: &str,
        bucket: &str,
        credentials: R2Credentials,
        http: Arc<dyn Http>,
        retry: Retry,
    ) -> Result<Self> {
        if account_id.len() != 32 || !account_id.bytes().all(|b| b.is_ascii_hexdigit()) {
            bail!("account_id must be the 32-character Cloudflare account id");
        }
        let host = match jurisdiction {
            "default" => format!("{account_id}.r2.cloudflarestorage.com"),
            "eu" | "fedramp" => format!("{account_id}.{jurisdiction}.r2.cloudflarestorage.com"),
            _ => bail!("jurisdiction must be default, eu or fedramp"),
        };
        let ok = (3..=63).contains(&bucket.len())
            && bucket
                .bytes()
                .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
            && !bucket.starts_with('-')
            && !bucket.ends_with('-');
        if !ok {
            bail!("bucket must be 3-63 lower-case letters, digits and hyphens");
        }
        Ok(Self {
            endpoint: Url::parse(&format!("https://{host}/"))?,
            bucket: bucket.to_owned(),
            credentials,
            http,
            retry,
            clock: Instant::now,
        })
    }

    #[doc(hidden)]
    pub fn with_clock(mut self, clock: fn() -> Instant) -> Self {
        self.clock = clock;
        self
    }

    fn url(&self, key: Option<&str>, query: &[(&str, &str)]) -> Result<Url> {
        let mut url = self.endpoint.clone();
        {
            let mut segments = url
                .path_segments_mut()
                .map_err(|_| anyhow::anyhow!("invalid R2 endpoint"))?;
            segments.clear().push(&self.bucket);
            if let Some(key) = key {
                validate_key(key)?;
                segments.extend(key.split('/'));
            }
        }
        if !query.is_empty() {
            url.query_pairs_mut().extend_pairs(query);
        }
        Ok(url)
    }

    async fn request(
        &self,
        method: &'static str,
        url: Url,
        extra: &[(&str, String)],
        body: Vec<u8>,
    ) -> Result<HttpReply> {
        self.retry
            .send(self.http.as_ref(), || {
                let mut headers: Vec<(String, String)> = extra
                    .iter()
                    .map(|(k, v)| ((*k).to_owned(), v.clone()))
                    .collect();
                sign_v4(
                    method,
                    &url,
                    &mut headers,
                    &body,
                    &SigningKey {
                        access_key_id: &self.credentials.access_key_id,
                        secret: &self.credentials.secret_access_key,
                        region: "auto",
                        service: "s3",
                    },
                    (self.clock)(),
                )?;
                Ok(HttpRequest {
                    method,
                    url: url.clone(),
                    headers,
                    body: body.clone(),
                })
            })
            .await
    }
}

impl ObjectStore for R2Store {
    fn describe(&self) -> String {
        format!("Cloudflare R2 {}{}", self.endpoint.as_str(), self.bucket)
    }
    fn put_new<'a>(
        &'a self,
        key: &'a str,
        bytes: Vec<u8>,
        content_type: &'a str,
    ) -> BoxFut<'a, Result<PutOutcome>> {
        Box::pin(async move {
            let reply = self
                .request(
                    "PUT",
                    self.url(Some(key), &[])?,
                    &[
                        ("if-none-match", "*".to_owned()),
                        ("content-type", content_type.to_owned()),
                    ],
                    bytes,
                )
                .await?;
            match reply.status {
                200 | 201 => Ok(PutOutcome::Created),
                412 => Ok(PutOutcome::AlreadyExists),
                // The bucket lock check runs before If-None-Match, so an existing
                // locked object answers 409 ObjectLockedByBucketPolicy.
                409 if xml_first(&reply.body, "Code").as_deref()
                    == Some("ObjectLockedByBucketPolicy") =>
                {
                    Ok(PutOutcome::AlreadyExists)
                }
                _ => Err(failure("archive write", &reply)),
            }
        })
    }
    fn get<'a>(&'a self, key: &'a str) -> BoxFut<'a, Result<Option<Vec<u8>>>> {
        Box::pin(async move {
            let reply = self
                .request("GET", self.url(Some(key), &[])?, &[], vec![])
                .await?;
            match reply.status {
                200 => Ok(Some(reply.body)),
                404 => Ok(None),
                _ => Err(failure("archive read", &reply)),
            }
        })
    }
    fn list<'a>(&'a self, prefix: &'a str) -> BoxFut<'a, Result<Vec<String>>> {
        Box::pin(async move {
            validate_prefix(prefix)?;
            let mut keys = Vec::new();
            let mut token: Option<String> = None;
            for _ in 0..100_000 {
                let mut query = vec![("list-type", "2"), ("prefix", prefix), ("max-keys", "1000")];
                if let Some(t) = token.as_deref() {
                    query.push(("continuation-token", t));
                }
                let reply = self
                    .request("GET", self.url(None, &query)?, &[], vec![])
                    .await?;
                if !reply.success() {
                    return Err(failure("archive listing", &reply));
                }
                for key in xml_texts(&reply.body, Some("Contents"), "Key")? {
                    if key.starts_with(prefix) && validate_key(&key).is_ok() {
                        keys.push(key);
                    }
                }
                let truncated = xml_first(&reply.body, "IsTruncated").as_deref() == Some("true");
                let next =
                    xml_first(&reply.body, "NextContinuationToken").filter(|t| !t.is_empty());
                match (truncated, next) {
                    (true, Some(next)) if Some(&next) != token.as_ref() => token = Some(next),
                    (true, _) => bail!("archive listing did not advance"),
                    (false, _) => {
                        keys.sort();
                        keys.dedup();
                        return Ok(keys);
                    }
                }
            }
            bail!("archive listing did not terminate")
        })
    }
    fn hold<'a>(&'a self, key: &'a str, hold_id: &'a str) -> BoxFut<'a, Result<HoldOutcome>> {
        Box::pin(async move {
            let bytes = self
                .get(key)
                .await?
                .ok_or_else(|| anyhow::anyhow!("held object not found"))?;
            let held = hold_key(hold_id, key)?;
            self.put_new(&held, bytes, "application/gzip").await?;
            Ok(HoldOutcome {
                method: "copied_to_hold_prefix",
                held_key: held,
            })
        })
    }
    fn release<'a>(&'a self, _: &'a str) -> BoxFut<'a, Result<()>> {
        Box::pin(async move { Ok(()) })
    }
    fn delete_refused<'a>(&'a self, key: &'a str) -> BoxFut<'a, Result<bool>> {
        Box::pin(async move {
            let reply = self
                .request("DELETE", self.url(Some(key), &[])?, &[], vec![])
                .await?;
            Ok(!reply.success())
        })
    }
    fn retention_until<'a>(&'a self, _: &'a str) -> BoxFut<'a, Result<Option<String>>> {
        // R2 locks are bucket rules, not object properties.
        Box::pin(async move { Ok(None) })
    }
}

/// Inputs to AWS Signature Version 4.
pub struct SigningKey<'a> {
    pub access_key_id: &'a str,
    pub secret: &'a str,
    pub region: &'a str,
    pub service: &'a str,
}

fn hmac_sha256(key: &[u8], data: &[u8]) -> Vec<u8> {
    hmac::sign(&hmac::Key::new(hmac::HMAC_SHA256, key), data)
        .as_ref()
        .to_vec()
}

fn hex(bytes: &[u8]) -> String {
    junction_watch::event::hex(bytes)
}

/// SigV4 derived signing key for `date` (`YYYYMMDD`).
pub fn signing_key(secret: &str, date: &str, region: &str, service: &str) -> Vec<u8> {
    let k_date = hmac_sha256(format!("AWS4{secret}").as_bytes(), date.as_bytes());
    let k_region = hmac_sha256(&k_date, region.as_bytes());
    let k_service = hmac_sha256(&k_region, service.as_bytes());
    hmac_sha256(&k_service, b"aws4_request")
}

fn uri_encode(value: &str, encode_slash: bool) -> String {
    let mut out = String::with_capacity(value.len());
    for b in value.bytes() {
        if b.is_ascii_alphanumeric()
            || matches!(b, b'-' | b'_' | b'.' | b'~')
            || (b == b'/' && !encode_slash)
        {
            out.push(b as char);
        } else {
            out.push_str(&format!("%{b:02X}"));
        }
    }
    out
}

/// Add `host`, `x-amz-date`, `x-amz-content-sha256` and `authorization` to
/// `headers`, signing every header present. `at` is the request time.
pub fn sign_v4(
    method: &str,
    url: &Url,
    headers: &mut Vec<(String, String)>,
    body: &[u8],
    key: &SigningKey<'_>,
    at: Instant,
) -> Result<()> {
    let stamp = at.to_rfc3339();
    let amz_date = format!(
        "{}{}{}T{}{}{}Z",
        &stamp[0..4],
        &stamp[5..7],
        &stamp[8..10],
        &stamp[11..13],
        &stamp[14..16],
        &stamp[17..19]
    );
    let date = &amz_date[..8];
    let host = match url.port() {
        Some(port) => format!("{}:{port}", url.host_str().unwrap_or_default()),
        None => url.host_str().unwrap_or_default().to_owned(),
    };
    let payload = sha256_hex(body);
    headers.retain(|(k, _)| !k.eq_ignore_ascii_case("authorization"));
    if !headers.iter().any(|(k, _)| k.eq_ignore_ascii_case("host")) {
        headers.push(("host".into(), host));
    }
    headers.push(("x-amz-date".into(), amz_date.clone()));
    headers.push(("x-amz-content-sha256".into(), payload.clone()));

    // The URL keeps its path percent-encoded; decode then re-encode per segment
    // so the canonical form is S3's, not the URL library's.
    let path = url
        .path_segments()
        .map(|segments| {
            segments
                .map(|s| {
                    let decoded = percent_decode(s);
                    uri_encode(&decoded, true)
                })
                .collect::<Vec<_>>()
                .join("/")
        })
        .unwrap_or_default();
    let canonical_uri = format!("/{path}");
    let mut query: Vec<(String, String)> = url
        .query_pairs()
        .map(|(k, v)| (uri_encode(&k, true), uri_encode(&v, true)))
        .collect();
    query.sort();
    let canonical_query = query
        .iter()
        .map(|(k, v)| format!("{k}={v}"))
        .collect::<Vec<_>>()
        .join("&");
    let mut canonical: Vec<(String, String)> = headers
        .iter()
        .map(|(k, v)| {
            (
                k.to_ascii_lowercase(),
                v.split_whitespace().collect::<Vec<_>>().join(" "),
            )
        })
        .collect();
    canonical.sort();
    let canonical_headers: String = canonical
        .iter()
        .map(|(k, v)| format!("{k}:{v}\n"))
        .collect();
    let signed_headers = canonical
        .iter()
        .map(|(k, _)| k.as_str())
        .collect::<Vec<_>>()
        .join(";");
    let request = format!(
        "{method}\n{canonical_uri}\n{canonical_query}\n{canonical_headers}\n{signed_headers}\n{payload}"
    );
    let scope = format!("{date}/{}/{}/aws4_request", key.region, key.service);
    let to_sign = format!(
        "AWS4-HMAC-SHA256\n{amz_date}\n{scope}\n{}",
        sha256_hex(request.as_bytes())
    );
    let signature = hex(&hmac_sha256(
        &signing_key(key.secret, date, key.region, key.service),
        to_sign.as_bytes(),
    ));
    headers.push((
        "authorization".into(),
        format!(
            "AWS4-HMAC-SHA256 Credential={}/{scope}, SignedHeaders={signed_headers}, Signature={signature}",
            key.access_key_id
        ),
    ));
    Ok(())
}

fn percent_decode(value: &str) -> String {
    let bytes = value.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%'
            && i + 2 < bytes.len()
            && let Ok(b) = u8::from_str_radix(&value[i + 1..i + 3], 16)
        {
            out.push(b);
            i += 3;
        } else {
            out.push(bytes[i]);
            i += 1;
        }
    }
    String::from_utf8_lossy(&out).into_owned()
}

